import { StatCard } from '@/components/dss/stat-card';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Dialog, DialogContent, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';
import type { ForecastResult } from '@/types';
import { router, usePage } from '@inertiajs/react';
import { Brain, LineChart, Search, Target } from 'lucide-react';
import { useMemo, useState } from 'react';

export default function Forecasting({
    latestForecast,
    forecastHistory = [],
}: {
    latestForecast?: ForecastResult;
    forecastHistory: ForecastResult[];
}) {
    const { flash } = usePage().props as any;

    const [infoModal, setInfoModal] = useState<{
        title: string;
        content: string;
    } | null>(null);

    const [search, setSearch] = useState('');
    const [modelFilter, setModelFilter] = useState('all');
    const [currentPage, setCurrentPage] = useState(1);

    const [itemsPerPage, setItemsPerPage] = useState(10);

    const filteredForecasts = useMemo(() => {
        return forecastHistory.filter((item) => {
            const period = `${item.year}-${String(item.month).padStart(2, '0')}`;
            const model = item.model_type?.toLowerCase() ?? '';

            const matchesSearch =
                period.includes(search.toLowerCase()) ||
                model.includes(search.toLowerCase());

            const matchesModel =
                modelFilter === 'all' || item.model_type === modelFilter;

            return matchesSearch && matchesModel;
        });
    }, [forecastHistory, search, modelFilter]);

    const uniqueModels = Array.from(
        new Set(forecastHistory.map((item) => item.model_type).filter(Boolean)),
    );

    const totalPages = Math.ceil(filteredForecasts.length / itemsPerPage);

    const paginatedForecasts = filteredForecasts.slice(
        (currentPage - 1) * itemsPerPage,
        currentPage * itemsPerPage,
    );

    const forecastingInfo = {
        predictionNextMonth: {
            title: 'Prediction Next Month',
            content:
                'Prediction Next Month is the estimated electricity consumption for the upcoming month generated by the trained Machine Learning model.\n\nFormula:\npredicted_consumption = RandomForestRegression(features)\n\nRandom Forest Formula:\npredicted_consumption = (tree_1_prediction + tree_2_prediction + tree_3_prediction + ... + tree_n_prediction) ÷ number_of_trees\n\nFeatures Used:\nyear, month, temperature, humidity, rainfall, solar_irradiance, peak_demand_kw, lag_1, lag_2, trend, month_sin, and month_cos\n\nProcess:\n1. The system collects historical electricity consumption and climate data.\n2. The dataset is cleaned and prepared during preprocessing.\n3. Additional forecasting features are generated.\n4. The Random Forest model creates multiple decision trees.\n5. Each decision tree produces its own predicted value.\n6. The system averages all tree predictions.\n7. The final average becomes the Prediction Next Month result.',
        },
        mae: {
            title: 'MAE',
            content:
                'MAE or Mean Absolute Error measures the average size of prediction errors made by the machine learning model.\n\nFormula:\nMAE = ( Σ | actual_value − predicted_value | ) / number_of_records\n\nLower MAE values indicate better prediction accuracy.',
        },
        r2Score: {
            title: 'R2 Score',
            content:
                'R2 Score measures how well the machine learning model explains the patterns and variations in the dataset. A value closer to 1 indicates better model performance.',
        },
        rmse: {
            title: 'RMSE',
            content:
                'RMSE or Root Mean Squared Error measures prediction error. It gives more weight to larger errors.\n\nLower RMSE means the model predictions are closer to the actual values.',
        },
    };

    return (
        <div className="space-y-6 p-6">
            <div className="flex items-center justify-between gap-4">
                <div>
                    <h1 className="text-2xl font-semibold">
                        Machine Learning Forecasting
                    </h1>
                    <p className="text-sm text-muted-foreground">
                        Train the model and predict next-month electricity consumption.
                    </p>
                </div>

                <div className="flex gap-2">
                    <Button
                        variant="outline"
                        onClick={() => router.post('/admin/forecasting/train')}
                    >
                        Train Model
                    </Button>

                    <Button onClick={() => router.post('/admin/forecasting/predict')}>
                        Predict Next Month
                    </Button>
                </div>
            </div>

            {flash?.success && (
                <div className="rounded-md border border-emerald-200 bg-emerald-50 px-4 py-2 text-sm text-emerald-700">
                    {flash.success}
                </div>
            )}

            {flash?.error && (
                <div className="rounded-md border border-red-200 bg-red-50 px-4 py-2 text-sm text-red-700">
                    {flash.error}
                </div>
            )}

            <div className="grid gap-4 md:grid-cols-4">
                <StatCard
                    title="Prediction Next Month"
                    icon={Brain}
                    value={`${latestForecast?.predicted_consumption_kwh ?? 0} kWh`}
                    onInfoClick={() => setInfoModal(forecastingInfo.predictionNextMonth)}
                />

                <StatCard
                    title="MAE"
                    value={latestForecast?.mae ?? 'Pending'}
                    icon={Target}
                    onInfoClick={() => setInfoModal(forecastingInfo.mae)}
                />

                <StatCard
                    title="R2 Score"
                    value={latestForecast?.r2_score ?? 'Pending'}
                    icon={LineChart}
                    onInfoClick={() => setInfoModal(forecastingInfo.r2Score)}
                />

                <StatCard
                    title="RMSE"
                    value={latestForecast?.rmse ?? 'Pending'}
                    icon={Target}
                    onInfoClick={() => setInfoModal(forecastingInfo.rmse)}
                />
            </div>

            <Card className="rounded-lg">
                <CardHeader>
                    <div className="flex flex-col gap-4 md:flex-row md:items-center md:justify-between">
                        <CardTitle>Forecast History Table</CardTitle>

                        <div className="flex flex-col gap-2 md:flex-row">
                            <div className="relative">
                                <Search className="absolute left-3 top-3 h-4 w-4 text-muted-foreground" />

                                <Input
                                    className="w-full pl-9 md:w-64"
                                    placeholder="Search period or model..."
                                    value={search}
                                    onChange={(event) => {
                                        setSearch(event.target.value);
                                        setCurrentPage(1);
                                    }}
                                />
                            </div>

                            <select
                                className="rounded-md border bg-background px-3 py-2 text-sm"
                                value={modelFilter}
                                onChange={(event) => {
                                    setModelFilter(event.target.value);
                                    setCurrentPage(1);
                                }}
                            >
                                <option value="all">All Models</option>

                                {uniqueModels.map((model) => (
                                    <option key={model} value={model}>
                                        {model}
                                    </option>
                                ))}
                            </select>
                            <select
                                className="rounded-md border bg-background px-3 py-2 text-sm"
                                value={itemsPerPage}
                                onChange={(event) => {
                                    setItemsPerPage(Number(event.target.value));
                                    setCurrentPage(1);
                                }}
                            >
                                <option value={10}>10</option>
                                <option value={50}>50</option>
                                <option value={100}>100</option>
                            </select>
                        </div>
                    </div>
                </CardHeader>

                <CardContent className="overflow-x-auto">
                    <table className="w-full text-sm">
                        <thead>
                            <tr className="border-b bg-muted/40 text-left">
                                <th className="px-3 py-3 font-semibold">Period</th>
                                <th className="px-3 py-3 font-semibold">Prediction</th>
                                <th className="px-3 py-3 font-semibold">Change</th>
                                <th className="px-3 py-3 font-semibold">RMSE</th>
                                <th className="px-3 py-3 font-semibold">Model</th>
                            </tr>
                        </thead>

                        <tbody>
                            {paginatedForecasts.length > 0 ? (
                                paginatedForecasts.map((item) => (
                                    <tr key={item.id} className="border-b">
                                        <td className="px-3 py-3">
                                            {item.year}-{String(item.month).padStart(2, '0')}
                                        </td>
                                        <td className="px-3 py-3">
                                            {item.predicted_consumption_kwh} kWh
                                        </td>
                                        <td className="px-3 py-3">
                                            {item.change_percent ?? 0}%
                                        </td>
                                        <td className="px-3 py-3">
                                            {item.rmse ?? '-'}
                                        </td>
                                        <td className="px-3 py-3">
                                            {item.model_type}
                                        </td>
                                    </tr>
                                ))
                            ) : (
                                <tr>
                                    <td
                                        colSpan={5}
                                        className="px-3 py-8 text-center text-muted-foreground"
                                    >
                                        No forecast history found.
                                    </td>
                                </tr>
                            )}
                        </tbody>
                    </table>

                    <div className="mt-4 flex flex-col gap-3 md:flex-row md:items-center md:justify-between">
                        <p className="text-sm text-muted-foreground">
                            Showing {paginatedForecasts.length} of{' '}
                            {filteredForecasts.length} forecasts
                        </p>

                        <div className="flex items-center gap-2">
                            <Button
                                variant="outline"
                                size="sm"
                                disabled={currentPage === 1}
                                onClick={() => setCurrentPage(currentPage - 1)}
                            >
                                Previous
                            </Button>

                            <span className="text-sm">
                                Page {currentPage} of {totalPages || 1}
                            </span>

                            <Button
                                variant="outline"
                                size="sm"
                                disabled={
                                    currentPage === totalPages ||
                                    totalPages === 0
                                }
                                onClick={() => setCurrentPage(currentPage + 1)}
                            >
                                Next
                            </Button>
                        </div>
                    </div>
                </CardContent>
            </Card>

            <Dialog open={!!infoModal} onOpenChange={() => setInfoModal(null)}>
                <DialogContent>
                    <DialogHeader>
                        <DialogTitle>{infoModal?.title}</DialogTitle>
                    </DialogHeader>

                    <p className="whitespace-pre-line text-sm leading-relaxed text-muted-foreground">
                        {infoModal?.content}
                    </p>
                </DialogContent>
            </Dialog>
        </div>
    );
}
